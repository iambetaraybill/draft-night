def main() -> int:
    here = pathlib.Path(__file__).resolve().parent
    target = here / "draft-night"

    if target.exists():
        print(f"\n  A folder already exists at {target}")
        print("  Rename or delete it first, so nothing of yours gets overwritten.\n")
        return 1

    raw = base64.b64decode("".join(ARCHIVE.split()))
    with tarfile.open(fileobj=io.BytesIO(raw), mode="r:gz") as tar:
        # Refuse anything trying to escape the target directory.
        for member in tar.getmembers():
            path = (here / member.name).resolve()
            if not str(path).startswith(str(here)):
                print(f"  Refusing suspicious path in archive: {member.name}")
                return 1
        tar.extractall(here)

    files = sorted(p for p in target.rglob("*") if p.is_file())
    print(f"\n  Unpacked {len(files)} files into {target}\n")
    for p in files:
        print(f"    {p.relative_to(target)}")

    python = "python" if sys.platform == "win32" else "python3"
    activate = (
        ".venv\\Scripts\\activate" if sys.platform == "win32"
        else "source .venv/bin/activate"
    )
    print(f"""
  Next, one line at a time:

    cd draft-night
    {python} -m venv .venv
    {activate}
    pip install -r requirements.txt
    {python} -m unittest discover -s tests -t . -p "test_*.py"
    {python} -m draftnight.server --fast

  The last command prints two web addresses. Open the one with
  ?host= in it, then open the /play one in a second tab.
""")
    return 0


if __name__ == "__main__":
    sys.exit(main())
